# Wayfinding belongs at a few decision points rather than every opening.
SPARSE_SIGN_LIMIT = 2
SPARSE_SIGN_SPACING_M = 12.0
SPARSE_BOARD_WIDTH_M = .60
SPARSE_BOARD_HEIGHT_M = .30
SPARSE_BOARD_CENTER_Z_M = 1.15


def _select_sparse_junctions(junctions):
    """Keep an early entry and one well-separated deep entry on the main road."""
    candidates=[]
    seen=set()
    for item in junctions:
        if 'LOOP RETURN' in str(item.get('label','')).upper():
            continue
        pos=np.asarray(item['position'],dtype=float)
        if pos.shape not in [(2,),(3,)] or not np.isfinite(pos).all():
            raise ValueError('Wayfinding position must contain finite XY coordinates')
        identity=str(item.get('branch_id',tuple(pos[:2])))
        if identity in seen:
            continue
        seen.add(identity)
        candidates.append(item)
    candidates.sort(key=lambda item:float(item['position'][0]))
    if not candidates:
        return []
    first=candidates[0]
    selected=[first]
    # The main galleries are straight in the authored layouts, so X measures
    # along-road separation and cannot be inflated by lateral wall placement.
    for item in reversed(candidates[1:]):
        if float(item['position'][0])-float(first['position'][0]) >= SPARSE_SIGN_SPACING_M:
            selected.append(item)
            break
    return selected[:SPARSE_SIGN_LIMIT]


def _board_position(item, floor_height, cave_field, main_center_y):
    """Find a wall-side support while keeping its full panel inside the cave.

    The support is outside the rover's .62m planning footprint plus the .15m
    conservative sign collider. Panel corners are tested at their real height.
    """
    pos=np.asarray(item['position'],dtype=float)
    dst=np.asarray(item['destination'],dtype=float)
    side=-1.0 if dst[1]-pos[1]>=0 else 1.0
    if 'sign_position' in item:
        supplied=np.asarray(item['sign_position'],dtype=float)
        if supplied.shape not in [(2,),(3,)] or not np.isfinite(supplied).all():
            raise ValueError('sign_position must contain finite XY coordinates')
        proposals=[tuple(supplied[:2])]
    else:
        proposals=[]
        for shift in [.25,-.30,.65,-.70]:
            bx=float(pos[0])+shift
            cy=float(main_center_y(bx))
            # Prefer an inconspicuous wall-side mount; try progressively closer
            # positions only when rough rock would swallow the panel corners.
            for distance in np.arange(1.60,.79,-.04):
                proposals.append((bx,cy+side*distance))
    angle=math.radians(float(item.get('yaw_deg',side*45.)))
    ca,sa=math.cos(angle),math.sin(angle)
    for bx,by in proposals:
        cy=float(main_center_y(bx))
        if abs(by-cy)<.80:
            continue
        bz=float(floor_height(bx,by))+.015
        points=[]
        # Include housing overhangs, not just the ink surface.
        for px in [-.04,.04]:
            for py in [-(SPARSE_BOARD_WIDTH_M+.028)/2,(SPARSE_BOARD_WIDTH_M+.028)/2]:
                for pz in [SPARSE_BOARD_CENTER_Z_M-(SPARSE_BOARD_HEIGHT_M+.028)/2,
                           SPARSE_BOARD_CENTER_Z_M+(SPARSE_BOARD_HEIGHT_M+.028)/2]:
                    points.append((bx+ca*px-sa*py,by+sa*px+ca*py,bz+pz))
        if all(cave_field(*p)>.025 for p in points):
            return (float(bx),float(by),bz)
    raise ValueError(f'No safe roadside position for sparse sign at {pos[:2].tolist()}')


def _arrow(draw,center,size,direction,color):
    """Simple solid arrows keep direction readable independent of fonts."""
    x,y=center; s=float(size)
    pts=np.array([[-.5,-.16],[.10,-.16],[.10,-.38],[.55,0],
                  [.10,.38],[.10,.16],[-.5,.16]])*s
    if direction=='left':pts[:,0]*=-1
    if direction in ['back','forward']:
        # Down arrow means retrace the route toward the outpost.
        pts=pts[:,[1,0]]
        if direction=='forward':pts[:,1]*=-1
    draw.polygon([tuple(p+[x,y]) for p in pts],fill=color)


def _bitmap(path,region,title,arrow,compact=False,return_board=False,color=None):
    w,h=(512,640) if compact else (1536,768)
    im=Image.new('RGB',(w,h),(18,24,29));d=ImageDraw.Draw(im)
    col=color or REGIONS.get(region,REGIONS['A'])['color']
    margin=22 if compact else 30
    d.rounded_rectangle((margin,margin,w-margin,h-margin),radius=18,outline=col,width=12)
    if compact:
        f=ImageFont.truetype(FONT,230)
        text=region;bb=d.textbbox((0,0),text,font=f)
        d.text(((w-(bb[2]-bb[0]))/2,48),text,font=f,fill=col)
        f2=ImageFont.truetype(FONT,68)
        bb=d.textbbox((0,0),title,font=f2)
        d.text(((w-(bb[2]-bb[0]))/2,343),title,font=f2,fill=(229,235,232))
        _arrow(d,(w/2,525),140,arrow,col)
    else:
        # Region badge, generously spaced high-contrast title, explicit return row.
        d.rounded_rectangle((65,70,325,410),radius=14,fill=col)
        f=ImageFont.truetype(FONT,245 if len(region)==1 else 135 if len(region)==2 else 100)
        bb=d.textbbox((0,0),region,font=f)
        d.text((195-(bb[2]-bb[0])/2,82),region,font=f,fill=(19,25,30))
        display='RETURN' if return_board else title
        size=89
        while size>36 and d.textbbox((0,0),display,font=ImageFont.truetype(FONT,size))[2]>1080:size-=2
        ftitle=ImageFont.truetype(FONT,size)
        d.text((385,107),display,font=ftitle,fill=(232,238,235))
        fsub=ImageFont.truetype(FONT,43)
        d.text((390,226),'LUNAR FIELD OPERATIONS',font=fsub,fill=(147,169,177))
        _arrow(d,(1265,350),285,'back' if return_board else arrow,col)
        d.line((70,465,w-70,465),fill=(74,89,97),width=5)
        _arrow(d,(160,595),140,'back',col)
        fr=ImageFont.truetype(FONT,67)
        d.text((300,550),'RETURN / OUTPOST',font=fr,fill=(226,232,230))
        tiny=ImageFont.truetype(FONT,27)
        d.text((75,685),'PASSIVE WAYFINDING  /  REGION MARKER',font=tiny,fill=(118,139,147))
    path.parent.mkdir(parents=True,exist_ok=True)
    im.save(path)
    return path


def generate_sign_textures(directory=None):
    """Reproducibly generate small local label assets; no network access."""
    directory=Path(directory or ROOT/'assets/signs')
    result={}
    for key,region in REGIONS.items():
        result[key]=_bitmap(directory/f'region_{key}.png',key,region['title'],region['arrow'])
        result[key+'_return']=_bitmap(directory/f'region_{key}_return.png',key,region['title'],'back',return_board=True)
    for region,index,_,_ in BEACONS:
        key=f'{region}_{index:02d}'
        result[key]=_bitmap(directory/f'beacon_{key}.png',region,f'{index:02d}','back',compact=True)
    return result


def _ink_material(stage,name,image):
    p='/World/Materials/Sign_'+name
    m=UsdShade.Material.Define(stage,p)
    s=UsdShade.Shader.Define(stage,p+'/Surface');s.CreateIdAttr('UsdPreviewSurface')
    s.CreateInput('roughness',Sdf.ValueTypeNames.Float).Set(.56)
    s.CreateInput('metallic',Sdf.ValueTypeNames.Float).Set(.05)
    uv=UsdShade.Shader.Define(stage,p+'/UV');uv.CreateIdAttr('UsdPrimvarReader_float2')
    uv.CreateInput('varname',Sdf.ValueTypeNames.Token).Set('st')
    uv.CreateOutput('result',Sdf.ValueTypeNames.Float2)
    tex=UsdShade.Shader.Define(stage,p+'/Texture');tex.CreateIdAttr('UsdUVTexture')
    tex.CreateInput('file',Sdf.ValueTypeNames.Asset).Set(Sdf.AssetPath(str(image)))
    tex.CreateInput('sourceColorSpace',Sdf.ValueTypeNames.Token).Set('sRGB')
    tex.CreateInput('st',Sdf.ValueTypeNames.Float2).ConnectToSource(uv.ConnectableAPI(),'result')
    tex.CreateOutput('rgb',Sdf.ValueTypeNames.Float3)
    s.CreateInput('diffuseColor',Sdf.ValueTypeNames.Color3f).ConnectToSource(tex.ConnectableAPI(),'rgb')
    # Passive printed surfaces are visible only when an actual lamp reaches them.
    s.CreateInput('emissiveColor',Sdf.ValueTypeNames.Color3f).Set(Gf.Vec3f(0.))
    m.CreateSurfaceOutput().ConnectToSource(s.ConnectableAPI(),'surface')
    return m


def _face(stage,path,width,height,center_z,mat,front=True):
    # Viewed from approach -X: image right is -Y, image up is +Z.
    x=-.033 if front else .033
    ysign=1 if front else -1
    vv=np.array([[x,ysign*width/2,center_z-height/2],
                 [x,-ysign*width/2,center_z-height/2],
                 [x,-ysign*width/2,center_z+height/2],
                 [x,ysign*width/2,center_z+height/2]],np.float32)
    q=UsdGeom.Mesh.Define(stage,path)
    q.CreatePointsAttr(Vt.Vec3fArray.FromNumpy(vv));q.CreateFaceVertexCountsAttr([4]);q.CreateFaceVertexIndicesAttr([0,1,2,3])
    q.CreateSubdivisionSchemeAttr('none')
    UsdGeom.PrimvarsAPI(q).CreatePrimvar('st',Sdf.ValueTypeNames.TexCoord2fArray,'vertex').Set(
        Vt.Vec2fArray([Gf.Vec2f(0,0),Gf.Vec2f(1,0),Gf.Vec2f(1,1),Gf.Vec2f(0,1)]))
    UsdShade.MaterialBindingAPI.Apply(q.GetPrim()).Bind(mat)
    return q


def _build_board(stage,path,pos,rotation,width,height,center_z,front_mat,rear_mat,metal,post,compact=False,wall_mount=False):
    xform(stage,path,pos,(0,0,rotation))
    box(stage,path+'/Plate',(0,0,center_z),(.06,width+.028,height+.028),metal,.009)
    if wall_mount:
        # Small brackets disappear into the rock behind the plate; no roadside
        # bollard or broad base competes with the narrow vehicle passage.
        for i,y in enumerate([-.23*width,.23*width]):
            box(stage,path+f'/WallBracket{i}',(.095,y,center_z),(.18,.025,.025),metal,.004)
    else:
        post_top=center_z-height/2+.025
        cylinder(stage,path+'/Post',(0,0,post_top/2),.025 if not compact else .016,post_top,post,collision=True)
        cylinder(stage,path+'/Foot',(0,0,.025),.11 if not compact else .065,.05,metal,collision=True)
    _face(stage,path+'/Front',width,height,center_z,front_mat,True)
    _face(stage,path+'/Back',width,height,center_z,rear_mat,False)
    # Small metal frame fasteners are visible at close range.
    for i,y in enumerate([-.43*width,.43*width]):
        for j,z in enumerate([center_z-.39*height,center_z+.39*height]):
            cylinder(stage,path+f'/Bolt{i}_{j}',(-.039,y,z),.007 if not compact else .004,.008,post,'X')


def build_signage(stage,junctions=None):
    """Build per-layout wayfinding; return collision/map metadata records.

    ``junctions`` is a list of {position:[x,y],label:str,destination:[x,y]}.
    Optional ``position`` Z, ``yaw_deg``, ``region`` and ``arrow`` are accepted.
    Supplied junctions are filtered to at most two entry signs, at least twelve
    metres apart; loop-return duplicates are omitted. None keeps legacy signs.
    """
    from .lunar_geometry import floor_height,cave_field,main_center_y
    custom = junctions is not None
    if custom:
        entries=[]
        images={}
        colors=[v['color'] for v in REGIONS.values()]
        for i,item in enumerate(_select_sparse_junctions(junctions)):
            pos=np.asarray(item['position'],dtype=float)
            dst=np.asarray(item['destination'],dtype=float)
            if pos.shape not in [(2,),(3,)] or dst.shape not in [(2,),(3,)] or not np.isfinite(pos).all() or not np.isfinite(dst).all():
                raise ValueError('Wayfinding position and destination must contain finite XY coordinates')
            rawlabel=str(item.get('label',f'J{i+1} / SURVEY ROUTE'))
            if '/' in rawlabel:
                badge,title=[part.strip() for part in rawlabel.split('/',1)]
            else:
                badge,title=str(item.get('region',i+1)),rawlabel
            badge=str(item.get('branch_id',item.get('region',badge.split()[-1]))).upper()[:3]
            delta=dst[:2]-pos[:2]
            board_pos=_board_position(item,floor_height,cave_field,main_center_y)
            direction=('left' if delta[1]>0 else 'right') if abs(delta[1])>abs(delta[0])*.6 else ('forward' if delta[0]>=0 else 'back')
            direction=item.get('arrow',direction)
            key=f'LayoutJunction_{i:02d}'
            color=colors[i%len(colors)]
            directory=ROOT/'assets/signs'
            identity=hashlib.sha256(repr((badge,title,direction,color)).encode()).hexdigest()[:12]
            images[key]=_bitmap(directory/f'{key}_{identity}.png',badge,title,direction,color=color)
            images[key+'_return']=_bitmap(directory/f'{key}_{identity}_return.png',badge,title,'back',return_board=True,color=color)
            entries.append({'key':key,'region':badge,'title':title,'label':rawlabel,
                'position':board_pos,'junction_position':pos[:2].tolist(),
                'destination':dst.tolist(),'yaw_deg':float(item.get('yaw_deg',(-1. if delta[1]>=0 else 1.)*45.)),'arrow':direction})
    else:
        images=generate_sign_textures()
        entries=[{'key':region,'region':region,'title':info['title'],
                  'label':f"{region} / {info['title']}",'position':info['junction'],
                  'yaw_deg':0.,'arrow':info['arrow']} for region,info in REGIONS.items()]
    materials={k:_ink_material(stage,k,v) for k,v in images.items()}
    metal=material(stage,'sign_brushed_alloy',(.26,.29,.30),.38,.72)
    post=material(stage,'sign_dark_post',(.085,.095,.10),.65,.4)
    records=[]
    for i,item in enumerate(entries):
        key=item['key'];pos=item['position']
        path=f'/World/Wayfinding/Junction_{i:02d}'
        width,height,center=(SPARSE_BOARD_WIDTH_M,SPARSE_BOARD_HEIGHT_M,SPARSE_BOARD_CENTER_Z_M) if custom else (.90,.46,1.36)
        _build_board(stage,path,pos,item['yaw_deg'],width,height,center,materials[key],materials[key+'_return'],metal,post,wall_mount=custom)
        records.append({'x':pos[0],'y':pos[1],'radius':.15,'height':center+height/2+.04,'kind':'wayfinding_sign',
                        'region':item['region'],'label':item['label'],'prim_path':path,
                        'position':list(pos),'yaw_deg':item['yaw_deg'],'front_normal':'-X','arrow':item['arrow'],
                        'destination':item.get('destination'),'junction_position':item.get('junction_position'),
                        'board_size_m':[width,height],'sparse_wayfinding':custom,
                        'mounting':'wall_brackets' if custom else 'post'})
    if not custom:
        for region,index,pos,yaw in BEACONS:
            name=f'{region}_{index:02d}';path='/World/Wayfinding/Beacon_'+name
            _build_board(stage,path,pos,yaw,.18,.225,.68,materials[name],materials[name],metal,post,compact=True)
            records.append({'x':pos[0],'y':pos[1],'radius':.09,'height':.83,'kind':'route_beacon',
                            'region':region,'label':f'{region} {index:02d} / RETURN','prim_path':path,
                            'position':list(pos),'yaw_deg':yaw})
    return records
